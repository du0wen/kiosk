import { describe, expect, it, beforeEach } from "vitest";
import { signServeToken, verifyServeToken } from "./serve-token";

describe("Multi-Tenant Boundary & Anti-IDOR Security Contract", () => {
  const secretKey = "test-secret-key-32-byte-hex-0123456789abcdef0123456789abcdef";

  beforeEach(() => {
    process.env.BETTER_AUTH_SECRET = secretKey;
  });

  describe("Serve-Token Multi-Tenant Gate", () => {
    it("validates token signed for the correct tenant organization", () => {
      const orgA = "org-tenant-alpha";
      const userA = "user-alice";

      const token = signServeToken(orgA, userA);
      const verified = verifyServeToken(token);

      expect(verified).not.toBeNull();
      expect(verified?.orgId).toBe(orgA);
      expect(verified?.userId).toBe(userA);
    });

    it("rejects token when used against a different tenant organization", () => {
      const orgA = "org-tenant-alpha";
      const orgB = "org-tenant-bravo";
      const userA = "user-alice";

      // Token generated by tenant A
      const tokenFromTenantA = signServeToken(orgA, userA);
      const verified = verifyServeToken(tokenFromTenantA);

      // Even though the signature is cryptographically valid, the tenant identity
      // does NOT match tenant B's required orgId.
      expect(verified?.orgId).toBe(orgA);
      expect(verified?.orgId === orgB).toBe(false);
    });

    it("rejects forged or tampered token payloads", () => {
      const orgA = "org-tenant-alpha";
      const userA = "user-alice";

      const token = signServeToken(orgA, userA);
      const [payloadB64, sig] = token.split(".");

      // Attacker tampers the payload to switch org to Tenant B
      const decoded = JSON.parse(Buffer.from(payloadB64, "base64url").toString("utf8"));
      decoded.o = "org-tenant-bravo";
      const tamperedB64 = Buffer.from(JSON.stringify(decoded)).toString("base64url");
      const tamperedToken = `${tamperedB64}.${sig}`;

      const verified = verifyServeToken(tamperedToken);
      expect(verified).toBeNull();
    });

    it("rejects expired tokens immediately", async () => {
      const orgA = "org-tenant-alpha";
      const userA = "user-alice";

      // Expired token (ttl = -100ms)
      const expiredToken = signServeToken(orgA, userA, -100);
      const verified = verifyServeToken(expiredToken);

      expect(verified).toBeNull();
    });

    it("rejects tokens signed with an outdated or rotated server secret", () => {
      const orgA = "org-tenant-alpha";
      const userA = "user-alice";

      process.env.BETTER_AUTH_SECRET = "old-secret-before-incident-rotation-1234567";
      const oldToken = signServeToken(orgA, userA);

      // Secret is rotated
      process.env.BETTER_AUTH_SECRET = "new-rotated-secret-post-incident-abcdef999";
      const verified = verifyServeToken(oldToken);

      expect(verified).toBeNull();
    });
  });
});
